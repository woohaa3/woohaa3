/**
 * 宿主身份契约：让外部工具**认出这台实例是谁**，而不是只看一个端口有没有响应。
 *
 * ## 为什么需要它
 *
 * 同一台机器上跑着多份 Woohaa 宿主是常态：打包版（`web-host`）、`pnpm dev` 的前后端、
 * 桌面壳随包宿主，各自的数据目录完全不同。它们的 HTTP 形状一模一样——`/api/canvases`
 * 都返回 200，画布 id 甚至能重合，但**同 id 的两张画布内容不同**（revision、节点数都不同）。
 *
 * 只靠「端口有响应」判定实例，会让外部工具有两个错法：
 * 1. 把同一个实例的两个面（dev 的 vite 页面端口与后端端口）当成两个实例；
 * 2. 把两套不同数据的宿主当成同一个实例，于是在 A 上选了画布、去改 B 上同 id 的画布。
 *
 * 所以实例身份必须有**可比较的指纹**：数据目录是其中最强的一个（它直接决定「这份数据是谁」），
 * 外加实例启动时刻，用来区分「同一个数据目录被先后启动过两次」。
 *
 * ## 这个端点为什么这么小
 *
 * 它要被扫描器在几十个端口上逐个调用，所以只回身份，不回任何业务数据（不列画布、不回设置）。
 * 任何体积大的内容都会让发现变成一次全量拉取。
 *
 * ## 安全边界
 *
 * 只回**本机可见的事实**（数据目录路径、版本、启动时刻、协议版本），不回凭据、配置内容、
 * 画布或用户数据。数据目录路径本身就是本机路径，对同机的本地进程不是秘密；对外部署时
 * 反代与身份校验由部署方负责（与 `/api/settings` 同一前提）。**不提供远程探活用途**：
 * 它回答「你是谁」，不回答「你能做什么」。
 *
 * @module contracts/backend/host-identity
 */

/** 宿主身份端点的路径：扫描器与所有客户端共用这一个常量。 */
export const HOST_IDENTITY_PATH = "/api/host/identity";

/**
 * 一次身份应答的载荷。
 *
 * 全部字段都是**可比较的事实**，不含任何可写能力：
 * - `instanceId`：实例指纹的稳定部分。同一份数据目录在同一进程生命周期内不变；
 * - `dataDir`：数据目录绝对路径。它是「这份数据归谁」最直接的判据；
 * - `startedAt`：本次进程启动时刻。同一数据目录被重启后 `instanceId` 变，据此能区分「同一份数据的两次启动」；
 * - `version`：宿主应用版本；与 `protocolVersion` 分开，后者是内部协议兼容性。
 */
export type HostIdentity = {
  /** 实例指纹：由数据目录与启动时刻派生，用于跨端口合并同一实例的多个面。 */
  instanceId: string;
  /** 数据目录绝对路径（本机路径，不含任何凭据）。 */
  dataDir: string;
  /** 本次进程启动时刻（ISO）。 */
  startedAt: string;
  /** 宿主应用版本；取不到时为空串（开发构建常见）。 */
  version: string;
  /** 内部协议版本；与 `WOOHAA3_PROTOCOL_VERSION` 同源。 */
  protocolVersion: number;
};

/**
 * 判定两份身份是否**同一个实例**。
 *
 * 判据是 `instanceId` 相等：它已经把数据目录与启动时刻合并进指纹，所以「同一数据目录被重启」
 * 会被判成不同实例（这正是想要的——重启后挂载状态之外的内存态都变了）。
 * @param left - 一份身份。
 * @param right - 另一份身份。
 * @returns 是否为同一实例。
 */
export function sameHostInstance(left: HostIdentity, right: HostIdentity): boolean {
  return left.instanceId === right.instanceId;
}
