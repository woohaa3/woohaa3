import { afterEach, expect, it, vi } from "vitest";
import { createRuntimeComponentsStore } from "./runtime-components.js";
afterEach(() => { vi.useRealTimers(); });
const response = (status: string) => new Response(JSON.stringify({ available: true, components: [{ id: "fixture-component", status }] }));
it("shares in-flight reads and polls once for all subscribers, then stops", async () => {
  vi.useFakeTimers();
  let finish!: (value: Response) => void;
  const fetcher = vi.fn(() => new Promise<Response>(resolve => { finish = resolve; }));
  const store = createRuntimeComponentsStore(fetcher);
  const off = store.subscribe(() => {});
  const off2 = store.subscribe(() => {});
  const first = store.refresh();
  expect(store.refresh()).toBe(first);
  expect(fetcher).toHaveBeenCalledTimes(1);
  finish(response("missing")); await first;
  expect(store.getSnapshot().snapshot?.components[0]?.status).toBe("missing");
  off(); off2();
  await vi.advanceTimersByTimeAsync(5000);
  expect(fetcher).toHaveBeenCalledTimes(1);
});
