// Command generrors 从 proto 的 FailureReason 枚举生成 Go 错误值。
//
// 分类只在 api/proto 定义一处；生成物是 errorsv1alpha1.ErrXxx（*errs.Error）。
// 由 api/package.json 的 gen 脚本调用，gen:check 会拦住"改了 proto 忘了生成"。
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"

	errorsv1alpha1 "woohaa3/api/gen/go/woohaa/errors/v1alpha1"
)

var acronyms = map[string]string{"id": "ID", "api": "API", "url": "URL", "tof": "TOF", "rbac": "RBAC"}

var domains = []string{
	"canvas", "subject", "rbac", "auth", "admin", "identity",
	"profile", "storage", "generation", "telemetry", "diagnostics", "tof", "compaction", "internal",
}

func pascal(token string) string {
	if v, ok := acronyms[token]; ok {
		return v
	}
	return strings.ToUpper(token[:1]) + token[1:]
}

func main() {
	enum := errorsv1alpha1.File_woohaa_errors_v1alpha1_errors_proto.Enums().ByName("FailureReason")
	if enum == nil {
		fail("FailureReason 枚举不存在")
	}
	var b strings.Builder
	b.WriteString("// Code generated by api/tools/generrors. DO NOT EDIT.\n\n")
	b.WriteString("package errorsv1alpha1\n\n")
	b.WriteString("import (\n\t\"connectrpc.com/connect\"\n\n\t\"woohaa3/api/errs\"\n)\n\n")
	b.WriteString("// 每个分类一个错误值：code / reason / message 都在值上。\n")
	b.WriteString("// 领域代码用 fmt.Errorf(\"%w\") 加上下文，边界用 errors.As 取回。\n")
	b.WriteString("var (\n")
	for i := 0; i < enum.Values().Len(); i++ {
		value := enum.Values().Get(i)
		if value.Number() == 0 {
			continue
		}
		options, ok := value.Options().(*descriptorpb.EnumValueOptions)
		if !ok {
			fail("枚举值选项类型异常: " + string(value.Name()))
		}
		text, _ := proto.GetExtension(options, errorsv1alpha1.E_Text).(string)
		wire, _ := proto.GetExtension(options, errorsv1alpha1.E_ConnectCode).(string)
		if text == "" || wire == "" {
			fail(fmt.Sprintf("%s 缺少 (text) 或 (connect_code) 选项", value.Name()))
		}
		name := strings.TrimPrefix(string(value.Name()), "FAILURE_REASON_")
		tokens := strings.Split(strings.ToLower(name), "_")
		domain := tokens[0]
		if !contains(domains, domain) {
			fail("未知域前缀: " + domain)
		}
		rest := tokens[1:]
		var varName strings.Builder
		varName.WriteString("Err")
		varName.WriteString(pascal(domain))
		for _, token := range rest {
			varName.WriteString(pascal(token))
		}
		fmt.Fprintf(&b, "\t%s = errs.New(connect.Code%s, %q, %q)\n",
			varName.String(), wireToGo(wire), domain+"."+strings.Join(rest, "_"), text)
	}
	b.WriteString(")\n")

	out := filepath.Join("gen", "go", "woohaa", "errors", "v1alpha1", "failures_gen.go")
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		fail("写入 " + out + " 失败: " + err.Error())
	}
	fmt.Println("generated", out)
}

func wireToGo(wire string) string {
	var b strings.Builder
	for _, part := range strings.Split(wire, "_") {
		if part == "" {
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}

func contains(items []string, target string) bool {
	for _, item := range items {
		if item == target {
			return true
		}
	}
	return false
}

func fail(msg string) {
	fmt.Fprintln(os.Stderr, "generrors:", msg)
	os.Exit(1)
}
